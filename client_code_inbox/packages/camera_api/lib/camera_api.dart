/// Pure-Dart, UI-independent camera-access API. No `package:flutter` dependency — see
/// design/stages/mobile-app-android-1-video-image-pipeline/DESIGN.md §2/§3. Both the app's UI
/// layer and, later, an in-app agent's tool registry are equal consumers of this package.
///
/// `lib/src/` layout (restructured 2026-08-11 for a cleaner hand-off surface — see
/// `kb/raw/2026-08-11-code-camera-api-lan-wan-restructure.md`):
///   - `camera_connection.dart`, `camera_result.dart` — shared by every client on both
///     transports, so they live at the root rather than under `lan/` or `wan/`.
///   - `night_vision_types.dart`, `mirror_flip_types.dart`, `privacy_mode_types.dart` — wire
///     enums + (for night vision) the transport-agnostic `NightVisionSource` interface, shared
///     by the matching `lan/nuraeye/*` and `wan/wan_*` client pair for that setting.
///   - `util/` — pure math/data helpers with no network call of any kind.
///   - `lan/onvif/` — ONVIF SOAP clients.
///   - `lan/nuraeye/` — the proprietary `/nuraeye/*` REST API: `NuraeyeClient` (hand-written,
///     what every other class here actually calls through) plus every `rest_*.dart` file
///     (machine-generated by `tools/generate_dart_rest_client.py`, currently unused by
///     `NuraeyeClient` — see that script's own doc for why both still exist).
///   - `lan/discovery/` — WS-Discovery (UDP multicast device discovery, not SOAP or REST).
///   - `wan/` — AWS IoT MQTT command relay + KVS playback, mirroring `lan/nuraeye/`'s settings
///     one-for-one where a WAN counterpart exists.
